//! The legacy ZeroTier dialect.
//!
//! ZeroTier's `node/` implementation uses several conventions that have no
//! equivalent in standard RustCrypto libraries. This module reproduces them
//! exactly, because a node that joins a ZeroTier network must produce
//! byte-identical signatures, key agreements, and credentials.
//!
//! # What is different from ZT-next
//!
//! | Concern | ZeroTier | ZT-next |
//! |---|---|---|
//! | Key set | 64 bytes: `C25519 ‖ Ed25519` | 32 bytes |
//! | Signature | 96 bytes, custom | 64 bytes, standard Ed25519 |
//! | Key agreement | SHA-512 counter-mode KDF | HKDF-SHA256 |
//! | AEAD | Salsa20/12 + Poly1305 | ChaCha20-Poly1305 |
//! | Address | 5 bytes, global | 10 bytes, per network |
//! | Credential | `CertificateOfMembership`, long-lived bearer | Short-lived, key-bound |
//!
//! The signature format is the hardest part. ZeroTier signs `SHA512(msg)`
//! and appends the raw first 32 bytes of that digest to the signature, so
//! `ed25519-dalek` cannot produce it directly.
//!
//! # Verification
//!
//! Every function here is checked against the golden vectors in
//! `vectors/legacy/`, which are generated by ZeroTier's own C++ code through
//! the oracle in `oracle/`.

use hkdf::Hkdf;
use sha2::{Digest, Sha256, Sha512};

/// Length of a Curve25519 key in the ZeroTier key set.
pub const C25519_LEN: usize = 32;

/// Length of an Ed25519 key in the ZeroTier key set.
pub const ED25519_LEN: usize = 32;

/// Total length of a ZeroTier key set.
pub const KEY_SET_LEN: usize = C25519_LEN + ED25519_LEN;

/// Length of a ZeroTier signature.
pub const SIG_LEN: usize = 96;

/// Length of a ZeroTier address.
pub const ADDRESS_LEN: usize = 5;

/// A ZeroTier node identity.
///
/// The key set is 64 bytes: the first 32 are the Curve25519 key used for key
/// agreement, the last 32 are the Ed25519 key used for signing.
#[derive(Clone)]
pub struct LegacyIdentity {
    key_set: [u8; KEY_SET_LEN],
}

impl LegacyIdentity {
    /// Build an identity from a raw key set.
    pub fn from_bytes(key_set: &[u8; KEY_SET_LEN]) -> Self {
        Self { key_set: *key_set }
    }

    /// The raw key set.
    pub fn key_set(&self) -> &[u8; KEY_SET_LEN] {
        &self.key_set
    }

    /// The Curve25519 half of the key set.
    pub fn c25519(&self) -> &[u8; C25519_LEN] {
        self.key_set[..C25519_LEN].try_into().expect("32 bytes")
    }

    /// The Ed25519 half of the key set.
    pub fn ed25519(&self) -> &[u8; ED25519_LEN] {
        self.key_set[C25519_LEN..].try_into().expect("32 bytes")
    }

    /// Derive this node's global ZeroTier address.
    ///
    /// The address comes from ZeroTier's memory-hard hash of the public key
    /// set, not from a plain digest. See [`crate::hashcash`] for why.
    pub fn address(&self) -> LegacyAddress {
        LegacyAddress(crate::hashcash::address_from_public_key(&self.key_set))
    }

    /// Whether this identity satisfies ZeroTier's hashcash condition.
    ///
    /// Identities whose memory-hard digest starts above the threshold are
    /// rejected by ZeroTier peers.
    pub fn satisfies_hashcash(&self) -> bool {
        crate::hashcash::satisfies_hashcash(&self.key_set)
    }

    /// Sign a message in ZeroTier's 96-byte format.
    ///
    /// The signature is `R(32) ‖ S(32) ‖ SHA512(msg)[0..32]`, where `R ‖ S`
    /// is a standard Ed25519 signature over the 32-byte truncated SHA-512
    /// digest of the message.
    ///
    /// The Ed25519 key is expanded the way ZeroTier does it: the seed is
    /// hashed with SHA-512 and the result is clamped, rather than using the
    /// seed directly.
    pub fn sign(&self, message: &[u8]) -> LegacySignature {
        let digest = Sha512::digest(message);
        let mut truncated = [0u8; 32];
        truncated.copy_from_slice(&digest[..32]);

        // Sign the truncated digest as if it were the message. This is the
        // custom step: standard Ed25519 would sign the full digest.
        use ed25519_dalek::Signer;
        let signing_key =
            ed25519_dalek::SigningKey::from_bytes(&expand_ed25519_seed(self.ed25519()));
        let ed_signature = signing_key.sign(&truncated).to_bytes();

        let mut out = [0u8; SIG_LEN];
        out[..64].copy_from_slice(&ed_signature);
        out[64..].copy_from_slice(&digest[..32]);
        LegacySignature(out)
    }

    /// Verify a ZeroTier-format signature.
    pub fn verify(
        public_key: &[u8; ED25519_LEN],
        message: &[u8],
        signature: &LegacySignature,
    ) -> bool {
        let digest = Sha512::digest(message);
        let mut truncated = [0u8; 32];
        truncated.copy_from_slice(&digest[..32]);

        let verifying_key = match ed25519_dalek::VerifyingKey::from_bytes(public_key) {
            Ok(key) => key,
            Err(_) => return false,
        };
        let mut ed_bytes = [0u8; 64];
        ed_bytes.copy_from_slice(&signature.0[..64]);
        let ed_signature = ed25519_dalek::Signature::from_bytes(&ed_bytes);
        use ed25519_dalek::Verifier;
        verifying_key.verify(&truncated, &ed_signature).is_ok()
    }

    /// Derive the Ed25519 public key for this identity.
    ///
    /// ZeroTier stores the public key in the key set, but a node that only
    /// holds the private half needs to recompute it.
    pub fn ed25519_public(&self) -> [u8; ED25519_LEN] {
        let expanded = expand_ed25519_seed(self.ed25519());
        ed25519_dalek::SigningKey::from_bytes(&expanded)
            .verifying_key()
            .to_bytes()
    }

    /// Compute the identity hash embedded in a Certificate of Membership.
    ///
    /// ZeroTier hashes this node's address together with its public key set
    /// using SHA-384. The first four 32-bit words of the digest are carried
    /// in the COM, which hardens the credential against replay by a node
    /// holding a different key.
    pub fn public_key_hash(&self) -> [u8; 48] {
        use sha2::Digest;
        let mut sha384 = sha2::Sha384::new();
        sha384.update(self.address().as_bytes());
        sha384.update(self.key_set);
        let out = sha384.finalize();
        let mut result = [0u8; 48];
        result.copy_from_slice(&out);
        result
    }
}

/// Expand an Ed25519 seed the way ZeroTier does.
///
/// ZeroTier hashes the 32-byte seed with SHA-512 and clamps the result,
/// rather than using the seed directly as the standard does.
pub fn expand_ed25519_seed(seed: &[u8; ED25519_LEN]) -> [u8; ED25519_LEN] {
    let mut extended = [0u8; 64];
    extended.copy_from_slice(&Sha512::digest(seed));
    extended[0] &= 248;
    extended[31] &= 127;
    extended[31] |= 64;
    let mut out = [0u8; ED25519_LEN];
    out.copy_from_slice(&extended[..ED25519_LEN]);
    out
}

impl core::fmt::Debug for LegacyIdentity {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str("LegacyIdentity([redacted])")
    }
}

/// A ZeroTier-format signature.
#[derive(Clone, PartialEq, Eq)]
pub struct LegacySignature([u8; SIG_LEN]);

impl LegacySignature {
    /// Wrap raw signature bytes.
    pub fn from_bytes(bytes: &[u8; SIG_LEN]) -> Self {
        Self(*bytes)
    }

    /// The raw signature bytes.
    pub fn as_bytes(&self) -> &[u8; SIG_LEN] {
        &self.0
    }
}

impl core::fmt::Debug for LegacySignature {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        f.write_str("LegacySignature([redacted])")
    }
}

/// A global ZeroTier address.
#[derive(Clone, Copy, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct LegacyAddress([u8; ADDRESS_LEN]);

impl LegacyAddress {
    /// The raw address bytes.
    pub fn as_bytes(&self) -> &[u8; ADDRESS_LEN] {
        &self.0
    }

    /// Build from raw bytes.
    pub fn from_bytes(bytes: &[u8; ADDRESS_LEN]) -> Self {
        Self(*bytes)
    }

    /// Render as lowercase hex.
    pub fn to_hex(&self) -> String {
        hex::encode(self.0)
    }
}

impl core::fmt::Debug for LegacyAddress {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "LegacyAddress({})", self.to_hex())
    }
}

impl core::fmt::Display for LegacyAddress {
    fn fmt(&self, f: &mut core::fmt::Formatter<'_>) -> core::fmt::Result {
        write!(f, "{}", self.to_hex())
    }
}

/// Whether an address falls in ZeroTier's reserved range.
///
/// ZeroTier reserves the zero address and addresses whose top bits fall in a
/// narrow window, so that real addresses cannot collide with special values.
pub fn is_reserved_address(address: &[u8; ADDRESS_LEN]) -> bool {
    address == &[0u8; ADDRESS_LEN] || address[0] == 0xff
}

/// ZeroTier's key agreement function.
///
/// This is the raw X25519 shared secret followed by a **hand-rolled
/// SHA-512 counter-mode KDF**. It is not HKDF and must be reproduced
/// exactly.
///
/// ```text
/// rawkey = X25519(mine, theirs)
/// digest = SHA512(rawkey)
/// for i in 0..keylen:
///     if k == 64: k = 0; digest = SHA512(digest)
///     keybuf[i] = digest[k]; k += 1
/// ```
pub fn agree(mine: &[u8; C25519_LEN], theirs: &[u8; C25519_LEN], key_len: usize) -> Vec<u8> {
    let raw = x25519_raw(mine, theirs);

    let mut digest = Sha512::digest(raw);
    let mut out = Vec::with_capacity(key_len);
    let mut offset = 0usize;

    while out.len() < key_len {
        if offset == 64 {
            digest = Sha512::digest(digest);
            offset = 0;
        }
        out.push(digest[offset]);
        offset += 1;
    }
    out
}

/// Raw X25519, without the all-zero output check.
///
/// ZeroTier uses the raw scalar multiplication. `x25519-dalek` rejects
/// low-order points, which ZeroTier does not, so the shared secret is
/// computed here directly from the scalar multiplication.
fn x25519_raw(mine: &[u8; C25519_LEN], theirs: &[u8; C25519_LEN]) -> [u8; 32] {
    use x25519_dalek::{PublicKey, StaticSecret};
    let secret = StaticSecret::from(*mine);
    let public = PublicKey::from(*theirs);
    secret.diffie_hellman(&public).to_bytes()
}

/// Derive the ZeroTier-style certificate properties hash.
///
/// ZeroTier's `CertificateOfMembership` binds the member ID, the network ID,
/// and the certificate's own properties hash.
pub fn properties_hash(member_id: &[u8; ADDRESS_LEN], network_id: u64) -> [u8; 32] {
    let mut hasher = Sha512::new();
    hasher.update(member_id);
    hasher.update(network_id.to_be_bytes());
    let digest = hasher.finalize();
    let mut out = [0u8; 32];
    out.copy_from_slice(&digest[..32]);
    out
}

/// HKDF-SHA256 helper for the legacy credential's key derivation.
///
/// Unlike ZeroTier's own `agree()`, this helper is used where ZT-next needs
/// a modern KDF while still being byte-compatible with the legacy wire
/// format.
///
/// Returns `false` when the requested output length is too long for HKDF.
pub fn derive_key(secret: &[u8], salt: &[u8], info: &[u8], out: &mut [u8]) -> bool {
    let hk = Hkdf::<Sha256>::new(Some(salt), secret);
    hk.expand(info, out).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn address_is_five_bytes() {
        let identity = LegacyIdentity::from_bytes(&[7u8; KEY_SET_LEN]);
        assert_eq!(identity.address().as_bytes().len(), 5);
    }

    #[test]
    fn address_is_deterministic() {
        let identity = LegacyIdentity::from_bytes(&[9u8; KEY_SET_LEN]);
        assert_eq!(identity.address(), identity.address());
    }

    #[test]
    fn the_address_comes_from_the_memory_hard_hash() {
        // The address is the last five bytes of the memory-hard digest.
        let identity = LegacyIdentity::from_bytes(&[7u8; KEY_SET_LEN]);
        let digest = crate::hashcash::memory_hard_hash(identity.key_set());
        let mut expected = [0u8; 5];
        expected.copy_from_slice(&digest[59..64]);
        assert_eq!(identity.address().as_bytes(), &expected);
    }

    #[test]
    fn reserved_addresses_are_possible_but_rejected() {
        // The memory-hard hash can produce a reserved address. ZeroTier
        // handles this by generating a new identity, not by patching the
        // address, so the value is reported as-is and the caller decides.
        let identity = LegacyIdentity::from_bytes(&[0u8; KEY_SET_LEN]);
        let address = identity.address();
        assert_eq!(address.as_bytes().len(), 5);
    }

    #[test]
    fn signature_is_ninety_six_bytes() {
        let identity = LegacyIdentity::from_bytes(&[3u8; KEY_SET_LEN]);
        let signature = identity.sign(b"payload");
        assert_eq!(signature.as_bytes().len(), 96);
    }

    #[test]
    fn signature_verifies_against_the_matching_key() {
        let identity = LegacyIdentity::from_bytes(&[4u8; KEY_SET_LEN]);
        let signature = identity.sign(b"payload");
        // The Ed25519 public key is derived from the expanded seed, not the
        // raw seed, so verify against the derived key.
        assert!(LegacyIdentity::verify(
            &identity.ed25519_public(),
            b"payload",
            &signature
        ));
    }

    #[test]
    fn signature_rejects_a_tampered_message() {
        let identity = LegacyIdentity::from_bytes(&[4u8; KEY_SET_LEN]);
        let signature = identity.sign(b"payload");
        assert!(!LegacyIdentity::verify(
            identity.ed25519(),
            b"payload!",
            &signature
        ));
    }

    #[test]
    fn signature_rejects_a_wrong_key() {
        let identity = LegacyIdentity::from_bytes(&[4u8; KEY_SET_LEN]);
        let signature = identity.sign(b"payload");
        let wrong = [5u8; ED25519_LEN];
        assert!(!LegacyIdentity::verify(&wrong, b"payload", &signature));
    }

    #[test]
    fn ed25519_public_key_matches_the_expanded_seed() {
        let identity = LegacyIdentity::from_bytes(&[6u8; KEY_SET_LEN]);
        let expected =
            ed25519_dalek::SigningKey::from_bytes(&expand_ed25519_seed(identity.ed25519()))
                .verifying_key()
                .to_bytes();
        assert_eq!(identity.ed25519_public(), expected);
    }

    #[test]
    fn agree_is_symmetric() {
        // Use real generated keys: arbitrary byte strings are not valid
        // X25519 scalars and would not produce a meaningful shared secret.
        let a = x25519_dalek::StaticSecret::random_from_rng(rand::rngs::OsRng);
        let b = x25519_dalek::StaticSecret::random_from_rng(rand::rngs::OsRng);
        let a_bytes = a.to_bytes();
        let b_bytes = b.to_bytes();
        let a_public = x25519_dalek::PublicKey::from(&a).to_bytes();
        let b_public = x25519_dalek::PublicKey::from(&b).to_bytes();

        let ab = x25519_raw(&a_bytes, &b_public);
        let ba = x25519_raw(&b_bytes, &a_public);
        assert_eq!(ab, ba);
    }

    #[test]
    fn agree_produces_the_requested_length() {
        let mine = x25519_dalek::StaticSecret::random_from_rng(rand::rngs::OsRng).to_bytes();
        let theirs = {
            let secret = x25519_dalek::StaticSecret::random_from_rng(rand::rngs::OsRng);
            x25519_dalek::PublicKey::from(&secret).to_bytes()
        };
        assert_eq!(agree(&mine, &theirs, 32).len(), 32);
        assert_eq!(agree(&mine, &theirs, 64).len(), 64);
        assert_eq!(agree(&mine, &theirs, 100).len(), 100);
    }

    #[test]
    fn agree_is_deterministic() {
        let mine = x25519_dalek::StaticSecret::random_from_rng(rand::rngs::OsRng).to_bytes();
        let theirs = {
            let secret = x25519_dalek::StaticSecret::random_from_rng(rand::rngs::OsRng);
            x25519_dalek::PublicKey::from(&secret).to_bytes()
        };
        assert_eq!(agree(&mine, &theirs, 64), agree(&mine, &theirs, 64));
    }

    #[test]
    fn reserved_addresses_are_detected() {
        assert!(is_reserved_address(&[0u8; 5]));
        assert!(is_reserved_address(&[0xff, 0, 0, 0, 0]));
        assert!(!is_reserved_address(&[1, 2, 3, 4, 5]));
    }
}
