//! # `zt-testvectors`
//!
//! Golden-vector infrastructure for the ZT-next protocol.
//!
//! This crate exists for one primary reason: **the legacy ZeroTier
//! compatibility shim (Track B) must produce byte-identical output to
//! ZeroTier's C++ `node/` implementation.** Verifying that requires a stable,
//! machine-readable vector format and a harness that can compare our Rust
//! implementation against an external oracle.
//!
//! ## Why a dedicated vector format
//!
//! Ad-hoc test fixtures scattered across crates do not scale across a
//! multi-track project. This crate defines a single on-disk format that:
//!
//! - is **language-agnostic** (JSON), so the C++ oracle can emit it too;
//! - is **versioned**, so vectors generated by an older build are detectable;
//! - records **provenance**, so a vector is never silently mixed up between
//!   the "next" protocol and the "legacy" shim.
//!
//! ## Track scope
//!
//! Vectors are tagged with a [`Track`] so that the two protocol generations
//! never contaminate each other:
//!
//! - [`Track::Next`] — the new ZT-next protocol. Vectors are generated by our
//!   own implementation and pinned to detect regressions.
//! - [`Track::Legacy`] — the ZeroTier-compatible shim. Vectors are generated
//!   by ZeroTier's C++ `node/` code and must be matched exactly.
//!
//! ## Typical use
//!
//! ```no_run
//! use zt_testvectors::{Track, VectorFile};
//!
//! let f: VectorFile = zt_testvectors::load("vectors/legacy/identity.json").unwrap();
//! assert_eq!(f.track, Track::Legacy);
//! ```

#![forbid(unsafe_code)]
#![warn(missing_docs)]

pub mod generate;

pub use generate::generate_all;

use serde::{Deserialize, Serialize};
use std::path::Path;

/// The protocol generation a vector belongs to.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Track {
    /// The new ZT-next protocol.
    Next,
    /// The ZeroTier-compatible legacy shim.
    Legacy,
}

impl Track {
    /// The directory name used for this track's vector files.
    pub fn dir_name(self) -> &'static str {
        match self {
            Track::Next => "next",
            Track::Legacy => "legacy",
        }
    }
}

/// Version of the vector format itself.
///
/// Bump this when the *structure* of a vector changes, not when values change.
pub const VECTOR_FORMAT_VERSION: u32 = 1;

/// A single golden test vector.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Vector {
    /// Format version, see [`VECTOR_FORMAT_VERSION`].
    pub version: u32,
    /// Which protocol generation this vector applies to.
    pub track: Track,
    /// The operation being tested, e.g. `identity.address`, `noise.handshake`.
    pub op: String,
    /// A human-readable description.
    pub description: String,
    /// Named inputs, hex-encoded.
    pub inputs: Vec<HexField>,
    /// Named outputs, hex-encoded.
    pub outputs: Vec<HexField>,
}

impl Vector {
    /// Create a new vector for the given track and operation.
    pub fn new(track: Track, op: impl Into<String>, description: impl Into<String>) -> Self {
        Self {
            version: VECTOR_FORMAT_VERSION,
            track,
            op: op.into(),
            description: description.into(),
            inputs: Vec::new(),
            outputs: Vec::new(),
        }
    }

    /// Add a hex-encoded input field.
    pub fn with_input(mut self, name: impl Into<String>, value: &[u8]) -> Self {
        self.inputs.push(HexField {
            name: name.into(),
            value: hex::encode(value),
        });
        self
    }

    /// Add a hex-encoded output field.
    pub fn with_output(mut self, name: impl Into<String>, value: &[u8]) -> Self {
        self.outputs.push(HexField {
            name: name.into(),
            value: hex::encode(value),
        });
        self
    }

    /// Look up an input by name.
    pub fn input(&self, name: &str) -> Option<Vec<u8>> {
        self.inputs
            .iter()
            .find(|f| f.name == name)
            .and_then(|f| hex::decode(&f.value).ok())
    }

    /// Look up an output by name.
    pub fn output(&self, name: &str) -> Option<Vec<u8>> {
        self.outputs
            .iter()
            .find(|f| f.name == name)
            .and_then(|f| hex::decode(&f.value).ok())
    }

    /// Serialize to pretty JSON.
    pub fn to_json(&self) -> String {
        serde_json::to_string_pretty(self).expect("vector is serializable")
    }
}

/// A named hex-encoded byte string.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct HexField {
    /// Field name.
    pub name: String,
    /// Hex-encoded value.
    pub value: String,
}

/// A collection of vectors, as stored on disk.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct VectorFile {
    /// Format version.
    pub version: u32,
    /// Which track this file belongs to.
    pub track: Track,
    /// The operation all vectors in this file exercise.
    pub op: String,
    /// The vectors.
    pub vectors: Vec<Vector>,
}

impl VectorFile {
    /// Create a new file for a track and operation.
    pub fn new(track: Track, op: impl Into<String>) -> Self {
        Self {
            version: VECTOR_FORMAT_VERSION,
            track,
            op: op.into(),
            vectors: Vec::new(),
        }
    }

    /// Add a vector.
    pub fn push(&mut self, vector: Vector) {
        self.vectors.push(vector);
    }

    /// Serialize to pretty JSON.
    pub fn to_json(&self) -> String {
        serde_json::to_string_pretty(self).expect("vector file is serializable")
    }

    /// Parse from JSON.
    pub fn from_json(s: &str) -> Result<Self, String> {
        let file: VectorFile = serde_json::from_str(s).map_err(|e| e.to_string())?;
        if file.version != VECTOR_FORMAT_VERSION {
            return Err(format!(
                "vector file version {} does not match expected {}",
                file.version, VECTOR_FORMAT_VERSION
            ));
        }
        Ok(file)
    }
}

/// Load a vector file from disk.
pub fn load(path: impl AsRef<Path>) -> Result<VectorFile, String> {
    let path = path.as_ref();
    let text = std::fs::read_to_string(path)
        .map_err(|e| format!("cannot read {}: {e}", path.display()))?;
    VectorFile::from_json(&text)
}

/// Write a vector file to disk, creating parent directories as needed.
pub fn save(path: impl AsRef<Path>, file: &VectorFile) -> Result<(), String> {
    let path = path.as_ref();
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|e| format!("cannot create {}: {e}", parent.display()))?;
    }
    std::fs::write(path, file.to_json())
        .map_err(|e| format!("cannot write {}: {e}", path.display()))
}

/// The canonical directory for a track's vectors.
pub fn vectors_dir(track: Track) -> String {
    format!("vectors/{}", track.dir_name())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn vector_roundtrips() {
        let v = Vector::new(Track::Next, "identity.address", "address derivation")
            .with_input("network_id", &[0u8; 8])
            .with_output("address", &[1u8; 10]);
        let json = v.to_json();
        let parsed: Vector = serde_json::from_str(&json).unwrap();
        assert_eq!(v, parsed);
        assert_eq!(parsed.output("address").unwrap(), &[1u8; 10]);
    }

    #[test]
    fn vector_file_roundtrips() {
        let mut f = VectorFile::new(Track::Legacy, "ecc.agree");
        f.push(
            Vector::new(Track::Legacy, "ecc.agree", "agreement")
                .with_input("secret", &[0xaa; 32])
                .with_output("shared", &[0xbb; 32]),
        );
        let json = f.to_json();
        let parsed = VectorFile::from_json(&json).unwrap();
        assert_eq!(f, parsed);
    }

    #[test]
    fn version_mismatch_is_rejected() {
        let mut f = VectorFile::new(Track::Next, "x");
        f.version = 999;
        let err = VectorFile::from_json(&f.to_json()).unwrap_err();
        assert!(err.contains("version"));
    }
}
